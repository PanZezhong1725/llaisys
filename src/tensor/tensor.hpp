// ============================================================
// 第 1 行：#pragma once
// ============================================================
#pragma once
// 这是一个“头文件守卫”，作用是防止这个头文件被重复包含（比如被多个 .cpp 文件 include 导致编译报错）。
// 相当于老式的 #ifndef ... #define ... #endif，写法更简洁。

// ============================================================
// 第 2 行：#include "../core/llaisys_core.hpp"
// ============================================================
#include "../core/llaisys_core.hpp"
// 引入上一层 core 目录下的核心头文件。
// 这里面大概率定义了基础类型，比如 llaisysDataType_t（数据类型枚举）、
// llaisysDeviceType_t（设备类型枚举）、core::storage_t（存储类）等。

// ============================================================
// 第 3 行：#include <vector>
// ============================================================
#include <vector>
// 引入 C++ 标准库的 vector（动态数组）。
// 后面用来存储张量的形状（shape）和步长（strides）。

// ============================================================
// 第 4 行：namespace llaisys {
// ============================================================
namespace llaisys {
// 定义一个命名空间叫 llaisys（可能是 "LLM AI System" 的缩写）。
// 作用是把所有相关的类、函数包在里面，防止和别的库（比如标准库）里的名字冲突。

// ============================================================
// 第 5 - 6 行：class Tensor; 和 using 别名
// ============================================================
class Tensor;
// 这行是“前向声明”（Forward Declaration）。
// 意思就是告诉编译器：“Tensor 是一个类，我待会儿再详细定义它”。
// 这里主要是为了第 7 行的 using 能提前用这个名字。

using tensor_t = std::shared_ptr<Tensor>;
// 这里定义了一个“类型别名”。
// std::shared_ptr<Tensor> 是 C++ 的“智能指针”，它会自动帮我们管理内存（不用手动 delete）。
// 这行意思是：以后我们写 tensor_t，就等价于写 std::shared_ptr<Tensor>。
// 以后创建张量都返回这个别名，非常安全。

// ============================================================
// 第 8 - 12 行：struct TensorMeta（张量元数据）
// ============================================================
struct TensorMeta {
    // struct 和 class 很像，区别是 struct 里的成员默认是公开的（public）。
    // 这个结构体用来存放张量的“形状信息”，不存具体数据。

    llaisysDataType_t dtype;
    // 数据类型，比如是 float32、int8 还是 bool。

    std::vector<size_t> shape;
    // 形状，比如 [2, 3, 4] 表示 2x3x4 的三维张量。
    // size_t 是无符号整数，用来表示大小。

    std::vector<ptrdiff_t> strides;
    // 步长（Strides），表示在某个维度上，移动到下一个元素需要在内存中跳过多少个元素。
    // ptrdiff_t 是有符号整数，可以处理负数（虽然这里通常是正数）。
};

// ============================================================
// 第 13 - 17 行：class Tensor 的主体开始
// ============================================================
class Tensor {
    // 这里开始定义真正的张量类。

    // ============================================================
    // 第 14 - 17 行：private（私有成员）
    // ============================================================
private:
    // private 表示下面的内容只能被这个类自己的函数访问，外部无法直接修改。

    TensorMeta _meta;
    // 上面定义的那个元数据结构体，存着 dtype、shape、strides。

    core::storage_t _storage;
    // 实际的“数据存储”对象。它是一个智能指针（看名字里的 _t 后缀）。
    // 它管理着真正存放字节数据的内存（可能在 CPU 内存条里，也可能在 GPU 显存里）。

    size_t _offset;
    // 偏移量（按字节数算）。因为多个张量可以共享同一块存储（比如切片操作），
    // 这个偏移量表示该张量的数据是从 _storage 的哪个位置开始的。
    // ============================================================
    // 第 18 行：私有构造函数（重点语法）
    // ============================================================
    Tensor(TensorMeta meta, core::storage_t storage, size_t offset = 0);
    // 这是构造函数，注意它被放在了 private 里面！
    // 这意味着：外部代码不能直接写 new Tensor(...) 或者 Tensor t(...) 来创建对象。
    // 为什么要这样做？因为创建张量很复杂（要判断 CPU 还是 GPU），所以强制用户使用下面的静态方法 create 来创建。
    // 参数最后的 "= 0" 表示 offset 有默认值 0，如果不传就默认为 0。

    // ============================================================
    // 第 19 行：public（公开成员）
    // ============================================================
public:
    // public 表示下面的内容谁都可以调用。

    // ============================================================
    // 第 20 - 24 行：静态工厂方法 create
    // ============================================================
    static tensor_t create(
        const std::vector<size_t> &shape,
        // 传入形状，这里用了 const &（常量引用），避免拷贝整个 vector，效率更高。

        llaisysDataType_t dtype,
        // 数据类型。

        llaisysDeviceType_t device_type = LLAISYS_DEVICE_CPU,
        // 设备类型，默认是 CPU。

        int device = 0);
    // 设备编号（比如有多张显卡时指定用哪张），默认是 0。
    // static 表示这个函数属于类本身，不需要对象就能调用。
    // 这就是唯一的“工厂方法”，内部会 new Tensor(...) 并返回智能指针。

    // ============================================================
    // 第 25 行：析构函数
    // ============================================================
    ~Tensor() = default;
    // 这是析构函数（对象销毁时调用）。
    // "= default" 是 C++11 的新语法，意思是“请编译器自动生成默认的析构函数实现”。
    // 因为用了智能指针 _storage，它自己会释放内存，所以我们不需要手动写代码。

    // ============================================================
    // 第 26 - 35 行：各种信息获取函数（Getter）
    // ============================================================
    // -------------------- 数据指针 --------------------
    std::byte *data();
    // 返回指向实际数据的指针（非 const 版本），允许修改数据。
    // std::byte 是 C++17 的字节类型，用来表示原始内存。

    const std::byte *data() const;
    // 这是 data() 的“常量重载版本”。
    // 重点看后面的 "const"：这个 const 表示该函数不会修改成员变量。
    // 如果外面有一个 const Tensor，就只能调用后面带 const 的 data()，拿到只读指针。

    // -------------------- 维度信息 --------------------
    size_t ndim() const;
    // 返回维度数量（比如 shape 是 [2,3,4]，则返回 3）。
    // 后面的 const 表示只是读取，不修改对象。

    const std::vector<size_t> &shape() const;
    // 返回形状的只读引用（const &）。这样不会拷贝整个 vector，效率高。
    // 外部只能看，不能改。

    const std::vector<ptrdiff_t> &strides() const;
    // 返回步长的只读引用。

    // -------------------- 类型和设备信息 --------------------
    llaisysDataType_t dtype() const;
    // 返回数据类型。

    llaisysDeviceType_t deviceType() const;
    // 返回设备类型（CPU 还是 GPU）。

    int deviceId() const;
    // 返回设备编号。

    // -------------------- 数量信息 --------------------
    size_t numel() const;
    // 返回元素总数（把所有 shape 乘起来）。

    size_t elementSize() const;
    // 返回单个元素占用的字节数（比如 float 占 4 字节）。

    // ============================================================
    // 第 37 - 38 行：信息打印
    // ============================================================
    std::string info() const;
    // 返回张量的描述信息（如 shape 和 dtype），以字符串形式。

    void debug() const;
    // 在控制台打印张量的具体数值内容（调试用）。

    // ============================================================
    // 第 40 行：连续性判断
    // ============================================================
    bool isContiguous() const;

    // 判断内存是否连续（即元素在内存里的排列顺序是否和 shape 的行优先顺序一致）。
    // 很多操作（比如 view）要求张量是连续的。

    // ============================================================
    // 第 42 - 45 行：元数据变换（轻量级，通常共享存储）
    // ============================================================
    // Meta Transform（只改变元数据，不拷贝数据）

    tensor_t permute(const std::vector<size_t> &order) const;
    // 重排维度（比如转置），返回新张量，但共享底层数据。

    tensor_t slice(size_t dim, size_t start, size_t end) const;
    // 在指定维度上切片（取一部分），返回新张量，共享底层数据。

    tensor_t view(const std::vector<size_t> &shape) const;
    // 改变视图形状（前提是内存连续），数据不变。

    // ============================================================
    // 第 47 - 48 行：数据加载
    // ============================================================
    // Load data from host memory
    void load(const void *src);
    // 从主机（CPU）内存加载数据到当前张量。
    // const void * 表示指向任意类型的只读指针，可以接收任何类型的数组。

    // ============================================================
    // 第 50 - 54 行：进阶操作（较难，会涉及数据拷贝）
    // ============================================================
    // Challenging features（有挑战性的功能）

    tensor_t contiguous() const;
    // 如果当前不连续，就创建一个新的连续存储，把数据按行优先顺序拷贝进去；
    // 如果已经连续，就返回自身。

    tensor_t reshape(const std::vector<size_t> &shape) const;
    // 相当于先确保连续，再调用 view。

    tensor_t to(llaisysDeviceType_t device_type, int device = -1) const;
    // 把张量迁移到另一个设备（比如从 CPU 搬到 GPU，或从 GPU 0 搬到 GPU 1）。
    // device = -1 表示使用该设备类型下的默认设备。

    // ============================================================
    // 第 55 行：命名空间结束
    // ============================================================
};
// 类定义结束。

} // namespace llaisys
// 命名空间结束。